#!/usr/bin/env python3
"""Embed every hero sprite set (assets/heroes/<name>/manifest.json + the files it references)
into assets.js as data URIs, so index.html also works when opened straight from disk (file://).
Run from anywhere:  python3 tools/build_assets.py"""
import base64, json, os
root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
heroes = os.path.join(root, 'assets', 'heroes')
out = {}
def uri(path):
    mime = 'image/png' if path.lower().endswith('.png') else 'image/jpeg' if path.lower().endswith(('.jpg', '.jpeg')) else 'image/webp'
    with open(path, 'rb') as fh: return f'data:{mime};base64,' + base64.b64encode(fh.read()).decode()
for name in sorted(os.listdir(heroes)):
    d = os.path.join(heroes, name); mf = os.path.join(d, 'manifest.json')
    if not os.path.isfile(mf): continue
    man = json.load(open(mf)); files = {}
    if man.get('portrait'): files[man['portrait']] = uri(os.path.join(d, man['portrait']))
    for anim, a in man['anims'].items():
        for dr in (man.get('dirs') or ['down', 'up', 'left', 'right']):
            f = a['file'].replace('{dir}', dr)
            if os.path.isfile(os.path.join(d, f)): files[f] = uri(os.path.join(d, f))
            else: print(f'warning: {name}/{f} missing')
    out[name] = {'manifest': man, 'files': files}
with open(os.path.join(root, 'assets.js'), 'w') as fh:
    fh.write('// GENERATED by tools/build_assets.py from assets/heroes/*/manifest.json -- do not edit by hand.\n')
    fh.write('const HERO_ASSET_DATA = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print('assets.js', os.path.getsize(os.path.join(root, 'assets.js')), 'bytes;', ', '.join(f'{k}: {len(v["files"])} files' for k, v in out.items()))
